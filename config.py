"""
Конфигурация бота
"""
import os
from dotenv import load_dotenv

# Загружаем переменные окружения из .env файла
load_dotenv()


class Config:
    """Класс конфигурации бота"""
    
    # Токен бота из переменных окружения
    BOT_TOKEN = os.getenv('BOT_TOKEN')
    
    # Проверка наличия токена
    if not BOT_TOKEN:
        raise ValueError("BOT_TOKEN не найден! Создайте файл .env и добавьте токен бота.")
    
    # Настройки викторины
    TOTAL_QUESTIONS = 15
    
    # Сообщения бота
    WELCOME_MESSAGE = """
🎮 Добро пожаловать в викторину!

Я задам вам {total} вопросов на различные темы.
Выбирайте правильный ответ из предложенных вариантов.

По окончании викторины вы увидите свои результаты! 📊

Готовы начать? Нажмите /start
    """.format(total=TOTAL_QUESTIONS)
    
    START_QUIZ_MESSAGE = "🚀 Отлично! Начинаем викторину!\n\n"
    
    CORRECT_ANSWER = "✅ Правильно! Отличная работа!"
    WRONG_ANSWER = "❌ Неправильно! Правильный ответ: {correct}"
    
    STATS_MESSAGE = """
📊 Ваша статистика:

✅ Правильных ответов: {correct}
❌ Неправильных ответов: {wrong}
📝 Всего вопросов: {total}
🎯 Процент правильных ответов: {percentage}%

{result_comment}
    """
    
    FINAL_STATS_MESSAGE = """
🏁 Викторина завершена!

📊 Итоговые результаты:

✅ Правильных ответов: {correct}
❌ Неправильных ответов: {wrong}
📝 Всего вопросов: {total}
🎯 Процент правильных ответов: {percentage}%

{result_comment}

Хотите пройти еще раз? Нажмите /restart
    """
    
    HELP_MESSAGE = """
ℹ️ Помощь по боту

Доступные команды:
/start - Начать викторину
/stats - Показать текущую статистику
/restart - Начать викторину заново
/help - Показать это сообщение

Как проходить викторину:
1. Нажмите /start
2. Прочитайте вопрос и посмотрите на картинку
3. Выберите правильный ответ из предложенных вариантов
4. Получите результаты после всех вопросов
    """
    
    @staticmethod
    def get_result_comment(percentage: float) -> str:
        """Получить комментарий в зависимости от результата"""
        if percentage == 100:
            return "🏆 ИДЕАЛЬНО! Вы ответили на все вопросы правильно!"
        elif percentage >= 80:
            return "🌟 ОТЛИЧНО! Вы показали отличные результаты!"
        elif percentage >= 60:
            return "👍 ХОРОШО! Неплохой результат, но можно лучше!"
        elif percentage >= 40:
            return "📚 УДОВЛЕТВОРИТЕЛЬНО! Рекомендуем пройти викторину еще раз!"
        else:
            return "💪 Не расстраивайтесь! Попробуйте еще раз, и результат будет лучше!"
